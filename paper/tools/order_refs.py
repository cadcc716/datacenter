#!/usr/bin/env python3
"""Number the references in the order of first citation (Applied Energy style).

Reads the \\bibitem entries of paper/references.tex and the \\citation lines of paper/manuscript.aux (written by LaTeX in
the order in which citations are typeset) and writes paper/sections/references_ordered.tex. Before the first LaTeX
run (no manuscript.aux) the file order is used. Cited keys without an entry and entries that are never cited are reported.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
src = open(os.path.join(ROOT, "references.tex"), encoding="utf-8").read()
body = "\n".join(l for l in src.splitlines() if not l.lstrip().startswith("%"))
items = {}
order_file = []
for m in re.finditer(r"\\bibitem\{([^}]+)\}(.*?)(?=\\bibitem\{|\Z)", body, re.S):
    key, text = m.group(1).strip(), " ".join(m.group(2).split())
    items[key] = text
    order_file.append(key)

cited = []
aux = os.path.join(ROOT, "manuscript.aux")
if os.path.exists(aux):
    for line in open(aux, encoding="utf-8", errors="replace"):
        m = re.match(r"\\citation\{([^}]*)\}", line)
        if m:
            for k in m.group(1).split(","):
                k = k.strip()
                if k and k not in cited:
                    cited.append(k)
missing = [k for k in cited if k not in items]
unused = [k for k in order_file if k not in cited] if cited else []
order = [k for k in cited if k in items] + unused if cited else order_file
with open(os.path.join(ROOT, "sections", "references_ordered.tex"), "w", encoding="utf-8") as f:
    f.write("% generated by tools/order_refs.py -- do not edit; edit references.tex instead\n")
    f.write("\\begin{thebibliography}{99}\n")
    for k in order:
        f.write(f"\\bibitem{{{k}}} {items[k]}\n")
    f.write("\\end{thebibliography}\n")
print(f"references: {len(order)} written, {len(cited)} cited", file=sys.stderr)
if missing:
    print("cited without entry: " + ", ".join(missing), file=sys.stderr)
if unused:
    print("entries never cited (kept at the end): " + ", ".join(unused), file=sys.stderr)
