function [row, hdr] = metrics_row(M)
%METRICS_ROW  Flatten the evaluation struct into a numeric row (for tables / CSV).
hdr = {'fulfil_rate_pct', 'n_valid', 'red_E1', 'red_E2', 'red_E3', 'rebound_E1', 'rebound_E2', 'rebound_E3', ...
       'max_rebound_MW', 'E_start_E1', 'E_start_E2', 'E_start_E3', 'B_start_E1', 'B_start_E2', 'B_start_E3', ...
       'cost_energy', 'cost_gas', 'cost_deg', 'cost_op', 'dr_pay', 'pen_dev', 'pen_rb', 'net_cost', ...
       'lateness_GPUh_h', 'peak_grid_MW', 'cap_violation_MW', 'bess_throughput_MWh', 'solve_time_s', 'fallbacks', ...
       'n_called', 'all_valid', 'true_red_E1', 'true_red_E2', 'true_red_E3', 'true_red_mean', ...
       'preload_mean_MW', 'preload_max_MW', 'preload_vs_nodr_MW', 'max_rebound6_MW', 'payback_gap_MWh', ...
       'payback_after_MWh', 'maxdev_after_MW', 'ramp_up_max_MW', 'peak_evening_MW', 'term_backlog_GPUh', ...
       'term_adj', 'cost_op_adj', 'net_cost_adj', 'net_cost_excl_rb', 'co2_t', 'gas_MWh', 'cost_delay', ...
       'pue', 'green_share_pv', 'cost_green', 'pue_excess_MWh', 'th_max_K', 'ramp_dn_max_MW', ...
       'res_selfuse', 'pause_ovh_GPUh', 'hp_MWh', 'heat_rec_MWh', 'boiler_MWh', 'cost_boiler', 'heat_rec_share'};
K = numel(M.avg_red); pad = @(v) [v(:)' nan(1, 3 - numel(v))];
k3 = 1:min(3, K);
row = [100 * M.fulfil_rate, M.n_valid, pad(M.avg_red(k3)), pad(M.rebound(k3)), M.max_rebound, ...
       pad(M.E_start(k3)), pad(sum(M.B_start(k3, :), 2)), ...
       M.cost_energy, M.cost_gas, M.cost_deg, M.cost_op, M.dr_pay, M.pen_dev, M.pen_rb, M.net_cost, ...
       M.lateness, M.peak_grid, M.cap_violation, M.bess_throughput, M.solve_time, M.fallbacks, ...
       M.n_called, M.all_valid, pad(M.true_red(k3)), M.true_red_mean, ...
       M.preload_mean, M.preload_max, M.preload_vs_nodr, M.max_rebound6, M.payback_gap, ...
       M.payback_after, M.maxdev_after, M.ramp_up_max, M.peak_evening, M.term_backlog, ...
       M.term_adj, M.cost_op_adj, M.net_cost_adj, M.net_cost_excl_rb, M.co2, M.gas_MWh, M.cost_delay, ...
       M.pue, M.green_share_pv, M.cost_green, M.pue_excess, M.th_max_K, M.ramp_dn_max, ...
       getm(M, 'res_selfuse'), getm(M, 'pause_ovh'), getm(M, 'hp_MWh'), getm(M, 'heat_rec_MWh'), getm(M, 'boiler_MWh'), ...
       getm(M, 'cost_boiler'), getm(M, 'heat_rec_share')];
end

function v = getm(M, f)
if isfield(M, f), v = M.(f); else, v = NaN; end
end
