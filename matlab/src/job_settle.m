function [M, row, hdr, S, L1] = job_settle(R, c, J, jo, L0)
%JOB_SETTLE  Execute a run at job level (JOB_REPLAY) and settle it again (EVALUATE_RUN).
%   R  : run (RUN_STRATEGY), c : its context, J : job population, jo : job-level options,
%   L0 : job-level log of the no-DR operation on the same day (reference of the settlement).
%   M  : metrics of the job-level execution; row/hdr: job-level statistics (see JOB_REPLAY);
%   L1 : job-level log.
[L1, S] = job_replay(R.log, c, J, jo);
M = evaluate_run(L1, c.ev, c.base, c.par, c.inp, L0);
K = numel(S.ev_dev);
hdr = [{'job_rmse_pg', 'job_max_dev'}, arrayfun(@(k) sprintf('job_ev_dev_E%d', k), 1:K, 'UniformOutput', false), ...
       {'job_over_defer', 'job_rec_short', 'job_extra_run', 'job_n_pause', 'job_n_paused_jobs', 'job_n_jobs', ...
        'job_ovh_GPUh', 'job_lost_GPUh', 'job_ovh_MWh', 'job_B_end', 'job_B_end_fluid', 'job_lateness', ...
        'job_lag_ratio_C1', 'job_lag_ratio_C2', 'job_lag_ratio_C3', 'job_late_share_C1', 'job_late_share_C2', ...
        'job_late_share_C3', 'job_step_max_MW', 'job_gang_max_MW', 'job_class_mae_C1', 'job_class_mae_C2', 'job_class_mae_C3'}];
row = [S.rmse_pg, S.max_dev, S.ev_dev(:)', S.over_defer, S.rec_short, S.extra_run, S.n_pause, S.n_paused_jobs, ...
       S.n_jobs, S.ovh_GPUh, S.lost_GPUh, S.ovh_MWh, S.B_end, S.B_end_fluid, S.lateness, S.lag_max_ratio(:)', ...
       S.late_share(:)', S.step_max_MW, S.gang_max_MW, S.class_mae(:)'];
end
